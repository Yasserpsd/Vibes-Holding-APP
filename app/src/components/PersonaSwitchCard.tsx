import Ionicons from '@expo/vector-icons/Ionicons';
import { useRouter, type Href } from 'expo-router';
import { StyleSheet, Text, View } from 'react-native';

import { useAuth } from '@/auth/AuthProvider';
import { GlassCard } from '@/components/lux';
import { PressScale } from '@/components/motion';
import { t } from '@/i18n';
import { textStart } from '@/i18n/direction';
import { colors, fonts, radii, spacing, typography } from '@/theme/tokens';

type Choice = 'entrepreneur' | 'investor';

/**
 * M74 (owner): the neutral's gentle standing card — «هل حددت وجهتك؟». One tap opens the
 * M101 persona screen, where the e-mailed code confirms the change (once every 30 days).
 */
export function PersonaSwitchCard() {
  const router = useRouter();
  const { me } = useAuth();

  if (!me || me.persona !== 'neutral') return null;

  const choose = (persona: Choice) => {
    // Typed routes are generated by expo; the new screen is not in the stale types yet.
    router.push(`/persona?pick=${persona}` as Href);
  };

  return (
    <GlassCard golden radius={radii.xl} style={styles.card}>
      <View style={styles.header}>
        <View style={styles.iconRing}>
          <Ionicons name="compass-outline" size={22} color={colors.gold} />
        </View>
        <Text style={styles.title}>{t('home.destination.title')}</Text>
      </View>
      <Text style={styles.text}>{t('home.destination.text')}</Text>
      <View style={styles.choices}>
        <ChoiceChip icon="rocket-outline" label={t('home.destination.entrepreneur')} onPress={() => choose('entrepreneur')} />
        <ChoiceChip icon="trending-up-outline" label={t('home.destination.investor')} onPress={() => choose('investor')} />
      </View>
      <Text style={styles.hint}>{t('persona.monthlyNote')}</Text>
    </GlassCard>
  );
}

function ChoiceChip({ icon, label, onPress }: { icon: 'rocket-outline' | 'trending-up-outline'; label: string; onPress: () => void }) {
  return (
    <PressScale onPress={onPress} glow glowRadius={radii.lg} wrapStyle={styles.choiceWrap} accessibilityRole="button" accessibilityLabel={label}>
      <View style={styles.choice}>
        <Ionicons name={icon} size={20} color={colors.gold} />
        <Text style={styles.choiceLabel} numberOfLines={1}>
          {label}
        </Text>
      </View>
    </PressScale>
  );
}

const styles = StyleSheet.create({
  card: { gap: spacing.sm, padding: spacing.md, marginTop: spacing.sm },
  header: { flexDirection: 'row', alignItems: 'center', gap: spacing.sm },
  iconRing: {
    width: 40,
    height: 40,
    borderRadius: radii.pill,
    alignItems: 'center',
    justifyContent: 'center',
    backgroundColor: colors.goldSoft,
  },
  title: { fontFamily: fonts.bold, fontSize: 18, lineHeight: 28, color: colors.gold, textAlign: textStart, flex: 1 },
  text: { ...typography.body, color: colors.textSecondary, textAlign: textStart },
  choices: { flexDirection: 'row', gap: spacing.sm },
  choiceWrap: { flex: 1 },
  choice: {
    flexDirection: 'row',
    alignItems: 'center',
    justifyContent: 'center',
    gap: spacing.xs,
    paddingVertical: spacing.sm + 2,
    paddingHorizontal: spacing.xs,
    borderRadius: radii.lg,
    borderWidth: 1,
    borderColor: colors.borderGoldSoft,
    backgroundColor: colors.surface,
  },
  choiceLabel: { fontFamily: fonts.semiBold, fontSize: 13, lineHeight: 20, color: colors.textPrimary },
  hint: { ...typography.caption, color: colors.textMuted, textAlign: textStart },
});
