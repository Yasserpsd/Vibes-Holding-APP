// Copies the app's wording (app/src/i18n/strings/*.json, the source of truth) into the server as
// src/appStrings/catalog.ts. The server is deployed from its own folder and cannot read app/ there:
// the dashboard's «نصوص التطبيق» section shows this copy next to the owner's edits, and a save is checked
// against it (known key, same {placeholders}). Run after every change of the app's strings:
//   npm run strings        (inside server/)
// `npm test` fails while the copy is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', 'app', 'src', 'i18n', 'strings');
const target = join(here, '..', 'src', 'appStrings', 'catalog.ts');

const read = (name) => JSON.parse(readFileSync(join(source, name), 'utf8'));
const ar = read('ar.json');
const en = read('en.json');
const groups = read('groups.json');

const missing = Object.keys(ar).filter((key) => !(key in en));
const extra = Object.keys(en).filter((key) => !(key in ar));
if (missing.length || extra.length) {
  console.error(`en.json does not match ar.json. Missing: ${missing.join(', ') || 'none'}. Extra: ${extra.join(', ') || 'none'}.`);
  process.exit(1);
}
const ungrouped = [...new Set(Object.keys(ar).map((key) => key.split('.')[0]))].filter((group) => !(group in groups));
if (ungrouped.length) {
  console.error(`groups.json has no label for: ${ungrouped.join(', ')}`);
  process.exit(1);
}

const body = `// GENERATED by scripts/sync-app-strings.mjs from app/src/i18n/strings. Do not edit: run \`npm run strings\`.
export const APP_STRINGS: { ar: Record<string, string>; en: Record<string, string>; groups: Record<string, string> } = ${JSON.stringify({ ar, en, groups }, null, 2)};
`;
writeFileSync(target, body);
console.log(`catalog.ts: ${Object.keys(ar).length} strings, ${Object.keys(groups).length} groups`);
